"""ARCH-D drawing sheets, drawn from the model rather than illustrated beside it.

Every sheet here is generated by reading the authored IFC — column positions, wall runs, space
polygons, grid spacing — so a sheet cannot drift from the model it documents. That is the whole
argument for generating them: a drawing produced by hand next to a model is a second source of truth
and will disagree with the first one eventually.

Output is SVG at ARCH-D (36 x 24 in / 914.4 x 609.6 mm), with a title block, graphic scale, north
arrow and a stated drawing status. Five sheets per project:

    G0.01   Cover sheet and project data
    A1.01   Overall floor plan, Level 1
    A2.01   Building elevations
    S2.01   Framing plan, typical level
    E2.01   Power and lighting plan, typical level
"""
from __future__ import annotations

import datetime as dt
import html

import projectdata as P

SHEET_W, SHEET_H = 914.4, 609.6         # ARCH-D, millimetres
MARGIN = 12.0
TB_X = 724.4                            # title-block divider
DRAW_W = TB_X - MARGIN * 2              # usable drawing width
INK = "#111"
THIN = "#555"
FAINT = "#999"
GRID = "#bbb"


def _esc(s) -> str:
    return html.escape(str(s), quote=True)


class Sheet:
    """An ARCH-D sheet. Coordinates are millimetres on the sheet."""

    def __init__(self, spec: dict, number: str, title: str, discipline: str):
        self.spec = spec
        self.number = number
        self.title = title
        self.discipline = discipline
        self.body: list[str] = []

    # ── primitives ───────────────────────────────────────────────────────────────────────────────
    def line(self, x1, y1, x2, y2, stroke=INK, w=0.3, dash=None):
        d = f' stroke-dasharray="{dash}"' if dash else ""
        self.body.append(f'<line x1="{x1:.2f}" y1="{y1:.2f}" x2="{x2:.2f}" y2="{y2:.2f}" '
                         f'stroke="{stroke}" stroke-width="{w}"{d}/>')

    def rect(self, x, y, w, h, stroke=INK, fill="none", sw=0.3, dash=None):
        d = f' stroke-dasharray="{dash}"' if dash else ""
        self.body.append(f'<rect x="{x:.2f}" y="{y:.2f}" width="{w:.2f}" height="{h:.2f}" '
                         f'fill="{fill}" stroke="{stroke}" stroke-width="{sw}"{d}/>')

    def circle(self, cx, cy, r, stroke=INK, fill="none", sw=0.3):
        self.body.append(f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{r:.2f}" fill="{fill}" '
                         f'stroke="{stroke}" stroke-width="{sw}"/>')

    def text(self, x, y, s, size=3.0, anchor="start", fill=INK, bold=False):
        self.body.append(
            f'<text x="{x:.2f}" y="{y:.2f}" font-size="{size}" text-anchor="{anchor}" '
            f'fill="{fill}" font-weight="{"bold" if bold else "normal"}" '
            f'font-family="Helvetica,Arial,sans-serif">{_esc(s)}</text>')

    def panel(self, x, y, w, h):
        """An opaque backing panel. The plan is fitted to fill the sheet, so title and legend blocks
        sit over it; without this they read as text tangled in the drawing."""
        self.body.append(f'<rect x="{x:.2f}" y="{y:.2f}" width="{w:.2f}" height="{h:.2f}" '
                         f'fill="#ffffff" fill-opacity="0.92" stroke="{GRID}" stroke-width="0.25"/>')

    def poly(self, pts, stroke=INK, fill="none", sw=0.3):
        d = " ".join(f"{x:.2f},{y:.2f}" for x, y in pts)
        self.body.append(f'<polygon points="{d}" fill="{fill}" stroke="{stroke}" '
                         f'stroke-width="{sw}"/>')

    # ── sheet furniture ──────────────────────────────────────────────────────────────────────────
    def title_block(self, scale_note: str = ""):
        s = self.spec
        self.rect(MARGIN, MARGIN, SHEET_W - MARGIN * 2, SHEET_H - MARGIN * 2, INK, "none", 1.0)
        self.line(TB_X, MARGIN, TB_X, SHEET_H - MARGIN, INK, 0.8)
        x = TB_X + 6
        self.text(x, 32, s["name"].upper(), 6.2, bold=True)
        self.text(x, 42, f'{s["subtype"].upper()} · SAMPLE PROJECT', 3.2, fill=THIN)
        self.line(x, 48, SHEET_W - MARGIN - 6, 48, INK, 0.4)

        rows = [
            ("PROJECT NO.", f'MSL-{s["key"][:6].upper()}'),
            ("SECTOR", s["sector"]),
            ("GROSS AREA", f'{s["gross_sf"]:,} sf'),
            ("STOREYS", str(s["storeys"])),
            ("STRUCTURE", s["structure"].title()),
            ("DISCIPLINE", self.discipline),
            ("SCALE", scale_note or "AS NOTED"),
            ("DATE", f"{dt.date.today():%d %b %Y}".upper()),
            ("ISSUE", "A — DESIGN DEVELOPMENT"),
        ]
        y = 60
        for label, val in rows:
            self.text(x, y, label, 2.5, fill=FAINT, bold=True)
            self.text(x, y + 4.6, val, 3.4)
            y += 12.5

        # The status note. A sample sheet that does not say what it is invites being cited as
        # something it is not.
        y += 4
        self.line(x, y, SHEET_W - MARGIN - 6, y, INK, 0.4)
        y += 8
        self.text(x, y, "NOT FOR CONSTRUCTION", 4.6, bold=True)
        for i, ln in enumerate([
                "Synthetic sample project. Generated from",
                "tools/sectors.py by tools/sheets.py. No",
                "part of this has been reviewed or sealed by",
                "a licensed professional, and no dimension",
                "has been verified against a built condition.",
                "Do not use to build, bid, or price."]):
            self.text(x, y + 7 + i * 4.4, ln, 2.7, fill=THIN)

        # Sheet number, bottom right — the thing people look for first.
        self.line(x, SHEET_H - MARGIN - 34, SHEET_W - MARGIN - 6, SHEET_H - MARGIN - 34, INK, 0.4)
        self.text(x, SHEET_H - MARGIN - 24, self.title.upper(), 3.4, bold=True)
        self.text(x, SHEET_H - MARGIN - 8, self.number, 11.0, bold=True)

    def north_arrow(self, cx, cy, r=7.0):
        self.circle(cx, cy, r, INK, "none", 0.4)
        self.poly([(cx, cy - r + 1), (cx - 2.6, cy + r - 2.5), (cx, cy + r - 4.5),
                   (cx + 2.6, cy + r - 2.5)], INK, INK, 0.3)
        self.text(cx, cy - r - 2, "N", 3.4, anchor="middle", bold=True)

    def scale_bar(self, x, y, mm_per_m: float, metres=(0, 5, 10, 20)):
        """A graphic scale, because a printed sheet's stated scale is only true at one paper size."""
        self.line(x, y, x + metres[-1] * mm_per_m, y, INK, 0.5)
        for m in metres:
            xx = x + m * mm_per_m
            self.line(xx, y - 1.8, xx, y + 1.8, INK, 0.5)
            self.text(xx, y + 6, str(m), 2.6, anchor="middle")
        self.text(x + metres[-1] * mm_per_m / 2, y - 4, "METRES", 2.4, anchor="middle", fill=THIN)

    # ── output ───────────────────────────────────────────────────────────────────────────────────
    def render(self) -> str:
        return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{SHEET_W}mm" '
                f'height="{SHEET_H}mm" viewBox="0 0 {SHEET_W} {SHEET_H}">'
                f'<rect x="0" y="0" width="{SHEET_W}" height="{SHEET_H}" fill="#fff"/>'
                + "".join(self.body) + "</svg>")


# ─────────────────────────────────────────────────────────────────────────────────────────────────
# Plan fitting
# ─────────────────────────────────────────────────────────────────────────────────────────────────
#: Annotation gutters, in SHEET millimetres. Grid bubbles, dimension strings and level tags are a
#: fixed size on paper no matter how big the building is, so the space they need is reserved in
#: millimetres. Expressing them in building metres — which an earlier version did — meant a 70 m
#: residential block pushed its own dimension line 89 mm off the left edge of the sheet, because a
#: 14 m offset scales with the plan and the text does not.
GUTTER_L, GUTTER_R, GUTTER_T, GUTTER_B = 34.0, 12.0, 24.0, 30.0


class Fit:
    """Maps building metres to sheet millimetres, centred in the drawing area, with the annotation
    gutters reserved so nothing lands off the sheet."""

    def __init__(self, spec: dict, pad: float = 14.0):
        w, d = spec["footprint"]
        avail_w = DRAW_W - pad * 2 - GUTTER_L - GUTTER_R
        avail_h = SHEET_H - MARGIN * 2 - pad * 2 - GUTTER_T - GUTTER_B
        self.k = min(avail_w / w, avail_h / d)
        left = MARGIN + pad + GUTTER_L
        top = MARGIN + pad + GUTTER_T
        self.ox = left + (avail_w - w * self.k) / 2
        self.oy = top + (avail_h + d * self.k) / 2            # flip Y: north up

    def x(self, mx: float) -> float:
        return self.ox + mx * self.k

    def y(self, my: float) -> float:
        return self.oy - my * self.k

    @property
    def ratio(self) -> str:
        """The true drawn ratio, e.g. 1:250."""
        return f"1:{round(1000 / self.k / 5) * 5}"


def _grid(spec):
    import geometry as G
    return G.grid_lines(spec)


def _draw_grid(sh: Sheet, fit: Fit, spec: dict):
    """Grid lines with bubbles. Bubble offsets are millimetres off the building edge, not metres."""
    xs, ys = _grid(spec)
    w, d = spec["footprint"]
    bub_y = fit.y(d) - 13.0          # 13 mm above the top of the plan
    bub_x = fit.x(0) - 13.0          # 13 mm left of it
    for i, x in enumerate(xs):
        sh.line(fit.x(x), fit.y(d) - 8.0, fit.x(x), fit.y(0) + 6.0, GRID, 0.2, "2,1.5")
        sh.circle(fit.x(x), bub_y, 3.4, THIN, "#fff", 0.3)
        sh.text(fit.x(x), bub_y + 1.2, chr(65 + i % 26), 2.8, "middle", THIN, True)
    for j, y in enumerate(ys):
        sh.line(fit.x(0) - 8.0, fit.y(y), fit.x(w) + 6.0, fit.y(y), GRID, 0.2, "2,1.5")
        sh.circle(bub_x, fit.y(y), 3.4, THIN, "#fff", 0.3)
        sh.text(bub_x, fit.y(y) + 1.2, str(j + 1), 2.8, "middle", THIN, True)


def _dim_string(sh: Sheet, fit: Fit, spec: dict):
    w, d = spec["footprint"]
    yy = fit.y(0) + 18.0             # 18 mm below the plan
    sh.line(fit.x(0), yy, fit.x(w), yy, INK, 0.3)
    for xx in (0, w):
        sh.line(fit.x(xx), yy - 2, fit.x(xx), yy + 2, INK, 0.3)
    sh.text(fit.x(w / 2), yy - 2.5, f"{w:.1f} m  ({w * 3.28084:.0f} ft)", 2.8, "middle")
    xx = fit.x(0) - 24.0             # 24 mm left of the plan
    sh.line(xx, fit.y(0), xx, fit.y(d), INK, 0.3)
    for yv in (0, d):
        sh.line(xx - 2, fit.y(yv), xx + 2, fit.y(yv), INK, 0.3)
    sh.text(xx - 3, fit.y(d / 2), f"{d:.1f} m  ({d * 3.28084:.0f} ft)", 2.8, "end")


